QString StripVersion(const QString & ActionName)
{
  QString Result = ActionName;
  while (!Result.isEmpty() && Result.back().isDigit())
  {
    Result.chop(1);
  }
  return Result;
}

// Keep in sync with slug() in tools/extract_glyphs.py
QString Slug(const QString & Name)
{
  static const QRegularExpression NonAlnum(QStringLiteral("[^a-z0-9]+"));
  QString Result = Name.toLower();
  Result.replace(NonAlnum, QStringLiteral("-"));
  while (Result.startsWith(QLatin1Char('-')))
  {
    Result.remove(0, 1);
  }
  while (Result.endsWith(QLatin1Char('-')))
  {
    Result.chop(1);
  }
  return Result;
}

