QIcon Icons::DialogImage(const QString & Name)
{
  static QHash<QString, QIcon> Cache;
  auto I = Cache.constFind(Name);
  if (I != Cache.constEnd())
  {
    return I.value();
  }

  QIcon Result;
  QString FileSlug = Slug(Name);
  for (int Size : AnimationSizes)
  {
    QString FileName = QStringLiteral(":/dialogs/%1/%2.png").arg(Size).arg(FileSlug);
    if (QFile::exists(FileName))
    {
      Result.addFile(FileName, QSize(Size, Size));
    }
  }
  // Like DoLoadDialogImage when the glyphs are not available (system icons)
  if (Result.isNull())
  {
    if (!HasGuiApplication())
    {
      return Result;
    }
    Result = FallbackIconFor(FallbackDialogImages, FileSlug);
  }
  Cache.insert(Name, Result);
  return Result;
}

QList<Icons::AnimationFrame> Icons::AnimationFrames(const QString & Name, int Size)
{
  // Frame file names are the WinSCP image names: <Name>_<FrameIndex>_<Duration>
  // (duration in 10 ms, see TFrameAnimation::CalculateNextFrameTick)
  QList<AnimationFrame> Result;
  QDir Dir(QStringLiteral(":/animations/%1").arg(Size));
  const QStringList Files = Dir.entryList({ Name + QStringLiteral("_*.png") }, QDir::Files);
  static const QRegularExpression FramePattern(QStringLiteral("^(\\w+?)_(-?\\d+)_(\\d+)\\.png$"));
  for (const QString & File : Files)
  {
    QRegularExpressionMatch Match = FramePattern.match(File);
    if (Match.hasMatch() && (Match.captured(1).compare(Name, Qt::CaseInsensitive) == 0))
    {
      AnimationFrame Frame;
      Frame.Pixmap = QPixmap(Dir.filePath(File));
      Frame.Index = Match.captured(2).toInt();
      Frame.Duration = Match.captured(3).toInt() * 10;
      Result.append(Frame);
    }
  }
  std::stable_sort(Result.begin(), Result.end(),
    [](const AnimationFrame & A, const AnimationFrame & B) { return A.Index < B.Index; });
  return Result;
}

