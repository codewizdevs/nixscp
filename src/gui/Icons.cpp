bool IconThemeInstalled(const QStringList & SearchPaths, const QString & Theme)
{
  return std::any_of(SearchPaths.cbegin(), SearchPaths.cend(),
    [&Theme](const QString & Path) { return QFileInfo::exists(Path + QLatin1Char('/') + Theme + QStringLiteral("/index.theme")); });
}

// Without a platform theme (offscreen, bare window managers) Qt has neither an
// icon search path nor a theme name, so QIcon::fromTheme finds nothing. Then use
// the XDG icon directories and the GTK icon theme setting, else a common theme.
void EnsureIconTheme()
{
  static bool Done = false;
  if (Done)
  {
    return;
  }
  Done = true;

  QStringList Paths = QIcon::themeSearchPaths();
  bool HasSystemPath = std::any_of(Paths.cbegin(), Paths.cend(),
    [](const QString & Path) { return !Path.startsWith(QLatin1Char(':')) && QFileInfo(Path).isDir(); });
  if (!HasSystemPath)
  {
    QStringList Dirs { QDir::homePath() + QStringLiteral("/.icons") };
    const QStringList DataDirs = QStandardPaths::standardLocations(QStandardPaths::GenericDataLocation);
    for (const QString & DataDir : DataDirs)
    {
      Dirs.append(DataDir + QStringLiteral("/icons"));
    }
    for (const QString & Dir : Dirs)
    {
      if (!Paths.contains(Dir) && QFileInfo(Dir).isDir())
      {
        Paths.append(Dir);
      }
    }
    QIcon::setThemeSearchPaths(Paths);
  }

  QString Theme = QIcon::themeName();
  if (Theme.isEmpty() || (Theme == QLatin1String("hicolor")))
  {
    QStringList Candidates;
    QString ConfigDir = QStandardPaths::writableLocation(QStandardPaths::GenericConfigLocation);
    for (const char * Gtk : { "gtk-4.0", "gtk-3.0" })
    {
      QSettings GtkSettings(ConfigDir + QLatin1Char('/') + QLatin1String(Gtk) + QStringLiteral("/settings.ini"), QSettings::IniFormat);
      QString Name = GtkSettings.value(QStringLiteral("Settings/gtk-icon-theme-name")).toString().trimmed();
      if (!Name.isEmpty())
      {
        Candidates.append(Name);
      }
    }
    // Xfce keeps it in xfconf (xsettings channel), not in the GTK settings.ini
    QFile Xsettings(ConfigDir + QStringLiteral("/xfce4/xfconf/xfce-perchannel-xml/xsettings.xml"));
    if (Xsettings.open(QIODevice::ReadOnly))
    {
      static const QRegularExpression XfceIconTheme(
        QStringLiteral("<property\\s+name=\"IconThemeName\"[^>]*\\bvalue=\"([^\"]+)\""));
      QRegularExpressionMatch Match = XfceIconTheme.match(QString::fromUtf8(Xsettings.readAll()));
      if (Match.hasMatch())
      {
        Candidates.append(Match.captured(1).trimmed());
      }
    }
    // KDE without the Plasma platform theme plugin
    QSettings KdeGlobals(ConfigDir + QStringLiteral("/kdeglobals"), QSettings::IniFormat);
    QString KdeTheme = KdeGlobals.value(QStringLiteral("Icons/Theme")).toString().trimmed();
    if (!KdeTheme.isEmpty())
    {
      Candidates.append(KdeTheme);
    }
    Candidates << QStringLiteral("breeze") << QStringLiteral("Papirus") << QStringLiteral("Yaru")
               << QStringLiteral("elementary-xfce") << QStringLiteral("elementary") << QStringLiteral("Adwaita")
               << QStringLiteral("oxygen") << QStringLiteral("Tango");
    // Breeze has monochrome (not "-symbolic") action icons: with a dark
    // palette its dark variant (what the KDE platform theme would pick)
    QPalette Palette = QGuiApplication::palette();
    bool DarkPalette = Palette.color(QPalette::WindowText).lightness() > Palette.color(QPalette::Window).lightness();
    for (const QString & Candidate : Candidates)
    {
      if (IconThemeInstalled(Paths, Candidate))
      {
        QString Dark = Candidate + QStringLiteral("-dark");
        bool UseDark = DarkPalette && (Candidate.compare(QStringLiteral("breeze"), Qt::CaseInsensitive) == 0) &&
          IconThemeInstalled(Paths, Dark);
        QIcon::setThemeName(UseDark ? Dark : Candidate);
        break;
      }
    }
  }
}

// Icon names (file names without extension) of the current icon theme, the
// themes it inherits, the fallback theme and hicolor. A QIcon::fromTheme miss is
// slow: Qt stats every directory of a theme folder without a valid
// icon-theme.cache (often ~/.local/share/icons/hicolor or
// /var/lib/snapd/desktop/icons/hicolor; 3-10 ms per miss) and repeats that for
// each shorter "dash fallback" name (view-sort-ascending, view-sort, view).
// One scan of the theme folders (~20 ms) lets ThemeIcon skip absent names.
class ThemeIconIndex
{
public:
  // false only if no theme folder has the name (call Update first)
  bool MayContain(const QString & Name) const
  {
    return FNames.isEmpty() || FNames.contains(Name);
  }

  // Rescans when the theme or the search paths changed
  void Update()
  {
    const QStringList Paths = QIcon::themeSearchPaths();
    QString Key = QIcon::themeName() + QLatin1Char('\n') + QIcon::fallbackThemeName() + QLatin1Char('\n') +
      Paths.join(QLatin1Char('\n')) + QLatin1Char('\n') + QIcon::fallbackSearchPaths().join(QLatin1Char('\n'));
    if (Key == FKey)
    {
      return;
    }
    FKey = Key;
    FNames.clear();
    // Like QIconTheme: every search path with the theme folder adds content,
    // the first index.theme gives the parents
    QStringList Pending { QIcon::themeName(), QIcon::fallbackThemeName(), QStringLiteral("hicolor") };
    QStringList Visited;
    while (!Pending.isEmpty())
    {
      QString Theme = Pending.takeFirst();
      if (Theme.isEmpty() || Visited.contains(Theme))
      {
        continue;
      }
      Visited.append(Theme);
      bool HasIndex = false;
      for (const QString & Path : Paths)
      {
        QString Dir = Path + QLatin1Char('/') + Theme;
        if (!QFileInfo(Dir).isDir())
        {
          continue;
        }
        QString IndexFile = Dir + QStringLiteral("/index.theme");
        if (!HasIndex && QFileInfo::exists(IndexFile))
        {
          HasIndex = true;
          QSettings Index(IndexFile, QSettings::IniFormat);
          Pending += Index.value(QStringLiteral("Icon Theme/Inherits")).toStringList();
        }
        Scan(Dir, 0);
      }
    }
    // Unthemed icons directly in the fallback search paths (e.g. /usr/share/pixmaps)
    const QStringList FallbackPaths = QIcon::fallbackSearchPaths();
    for (const QString & Path : FallbackPaths)
    {
      Scan(Path, -1);
    }
  }

private:
  static bool IsIconFile(QStringView FileName, qsizetype & Dot)
  {
    Dot = FileName.lastIndexOf(QLatin1Char('.'));
    if (Dot <= 0)
    {
      return false;
    }
    QStringView Ext = FileName.mid(Dot + 1);
    return (Ext == u"png") || (Ext == u"svg") || (Ext == u"svgz") || (Ext == u"xpm");
  }

  // Depth < 0: Dir only. Descends by hand instead of QDirIterator::Subdirectories,
  // which does not enter symlinked folders (Papirus-Dark links contexts to
  // Papirus) and FollowSymlinks would stat every symlinked icon (most Yaru
  // icons are). Only entries that are not icon files are checked for folders.
  void Scan(const QString & Dir, int Depth)
  {
    QDirIterator It(Dir, QDir::AllEntries | QDir::NoDotAndDotDot | QDir::System);
    while (It.hasNext())
    {
      It.next();
      const QString FileName = It.fileName();
      qsizetype Dot = 0;
      if (IsIconFile(FileName, Dot))
      {
        FNames.insert(FileName.left(Dot));
      }
      else if ((Depth >= 0) && (Depth < MaxScanDepth) && It.fileInfo().isDir())
      {
        Scan(It.filePath(), Depth + 1);
      }
    }
  }

  // <theme>/<size>/<context>/<icon> plus some slack; also stops symlink loops
  static constexpr int MaxScanDepth = 4;

  QString FKey;
  QSet<QString> FNames;
};

// The first of the space separated freedesktop Names the icon theme has.
// Exact names only: QIcon::fromTheme would also accept a shorter "dash fallback"
// (folder-new -> folder). Adwaita and Yaru have many actions only as -symbolic.
QString ThemeIconName(const QString & Names)
{
  static ThemeIconIndex Index;
  EnsureIconTheme();
  Index.Update();
  const QStringList Candidates = Names.split(QLatin1Char(' '), Qt::SkipEmptyParts);
  for (const QString & Candidate : Candidates)
  {
    for (const QString & Name : { Candidate, Candidate + QStringLiteral("-symbolic") })
    {
      if (Index.MayContain(Name) && QIcon::hasThemeIcon(Name))
      {
        return Name;
      }
    }
  }
  return QString();
}

// GTK recolors "-symbolic" icons to the text color; Qt draws them as they
// are (dark grey), which nearly vanishes with a dark palette (GNOME dark
// style, Breeze Dark with the Adwaita/Yaru icon themes). Monochrome by
// design, so the alpha channel is kept and filled with the palette color.
class SymbolicIconEngine : public QIconEngine
{
public:
  explicit SymbolicIconEngine(const QIcon & Base) : FBase(Base) {}

  QIconEngine * clone() const override { return new SymbolicIconEngine(FBase); }
  QString key() const override { return QStringLiteral("NixSCPSymbolic"); }
  QList<QSize> availableSizes(QIcon::Mode, QIcon::State) override { return FBase.availableSizes(); }
  QSize actualSize(const QSize & Size, QIcon::Mode Mode, QIcon::State State) override
  {
    return FBase.actualSize(Size, Mode, State);
  }
  QString iconName() override { return FBase.name(); }
  bool isNull() override { return FBase.isNull(); }

  QPixmap pixmap(const QSize & Size, QIcon::Mode Mode, QIcon::State State) override
  {
    return scaledPixmap(Size, Mode, State, 1.0);
  }

  QPixmap scaledPixmap(const QSize & Size, QIcon::Mode Mode, QIcon::State State, qreal Scale) override
  {
    QColor Color = TextColor(Mode);
    QString CacheKey = QStringLiteral("%1x%2@%3/%4/%5").arg(Size.width()).arg(Size.height()).arg(Scale).arg(Color.rgba()).arg(int(State));
    auto I = FCache.constFind(CacheKey);
    if (I != FCache.constEnd())
    {
      return I.value();
    }
    QPixmap Result = FBase.pixmap(Size, Scale, QIcon::Normal, State);
    if (!Result.isNull())
    {
      QImage Image = Result.toImage().convertToFormat(QImage::Format_ARGB32_Premultiplied);
      QPainter Painter(&Image);
      Painter.setCompositionMode(QPainter::CompositionMode_SourceIn);
      Painter.fillRect(Image.rect(), Color);
      Painter.end();
      QPixmap Recolored = QPixmap::fromImage(Image);
      Recolored.setDevicePixelRatio(Result.devicePixelRatio());
      Result = Recolored;
    }
    if (FCache.size() > 64)
    {
      FCache.clear();
    }
    FCache.insert(CacheKey, Result);
    return Result;
  }

  void paint(QPainter * Painter, const QRect & Rect, QIcon::Mode Mode, QIcon::State State) override
  {
    qreal Scale = (Painter->device() != nullptr) ? Painter->device()->devicePixelRatioF() : 1.0;
    QPixmap Pixmap = scaledPixmap(Rect.size(), Mode, State, Scale);
    Painter->drawPixmap(Rect, Pixmap);
  }

private:
  static QColor TextColor(QIcon::Mode Mode)
  {
    QPalette Palette = QGuiApplication::palette();
    switch (Mode)
    {
      case QIcon::Disabled: return Palette.color(QPalette::Disabled, QPalette::WindowText);
      case QIcon::Selected: return Palette.color(QPalette::Active, QPalette::HighlightedText);
      default: return Palette.color(QPalette::Active, QPalette::WindowText);
    }
  }

  QIcon FBase;
  QHash<QString, QPixmap> FCache;
};

QIcon ThemeIcon(const QString & Names)
{
  QString Name = ThemeIconName(Names);
  if (Name.isEmpty())
  {
    return QIcon();
  }
  QIcon Result = QIcon::fromTheme(Name);
  if (Name.endsWith(QStringLiteral("-symbolic")) && !Result.isNull())
  {
    Result = QIcon(new SymbolicIconEngine(Result));
  }
  return Result;
}

// Theme icon of Name from a fallback table, else its QStyle standard icon
template<std::size_t N>
QIcon FallbackIconFor(const FallbackIcon (&Table)[N], const QString & Name)
{
  QIcon Result;
  for (const FallbackIcon & Fallback : Table)
  {
    if (Name == QLatin1String(Fallback.Icon))
    {
      Result = ThemeIcon(QLatin1String(Fallback.Theme));
      if (Result.isNull() && (Fallback.Pixmap != QStyle::SP_CustomBase) &&
          (qobject_cast<QApplication *>(QCoreApplication::instance()) != nullptr))
      {
        Result = QApplication::style()->standardIcon(Fallback.Pixmap);
      }
      break;
    }
  }
  return Result;
}

