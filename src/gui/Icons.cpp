QIcon Icons::Get(const QString & Name)
{
  static QHash<QString, QIcon> Cache;
  auto I = Cache.constFind(Name);
  if (I != Cache.constEnd())
  {
    return I.value();
  }

  QIcon Result;
  for (int Size : IconSizes)
  {
    QString FileName = QStringLiteral(":/icons/%1/%2.png").arg(Size).arg(Name);
    if (QFile::exists(FileName))
    {
      Result.addFile(FileName, QSize(Size, Size));
    }
  }

  if (Result.isNull())
  {
    if (!HasGuiApplication())
    {
      return Result; // theme and style icons need the application object; not cached
    }
    Result = FallbackIconFor(FallbackIcons, Name);
    if (Result.isNull())
    {
      qWarning("Icons::Get: no icon \"%s\"", qPrintable(Name));
    }
  }

  Cache.insert(Name, Result);
  return Result;
}

QString Icons::ActionIconName(const QString & ActionName)
{
  static QHash<QString, QString> Exact;
  static QHash<QString, QString> Unversioned;
  if (Exact.isEmpty())
  {
    for (const ActionIcon & Entry : ActionIcons)
    {
      QString Action = QLatin1String(Entry.Action);
      QString Icon = QLatin1String(Entry.Icon);
      Exact.insert(Action, Icon);
      QString Stripped = StripVersion(Action);
      if (!Unversioned.contains(Stripped))
      {
        Unversioned.insert(Stripped, Icon);
      }
    }
  }
  QString Result = Exact.value(ActionName);
  if (Result.isEmpty())
  {
    Result = Unversioned.value(StripVersion(ActionName));
  }
  return Result;
}

QIcon Icons::ForAction(const QString & ActionName)
{
  QString Name = ActionIconName(ActionName);
  return Name.isEmpty() ? QIcon() : Get(Name);
}

