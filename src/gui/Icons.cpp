FrameAnimation::FrameAnimation(QWidget * Parent) :
  QWidget(Parent),
  FFirstLoopFrame(-1),
  FCurrentFrame(-1),
  FTimer(new QTimer(this))
{
  FTimer->setSingleShot(true);
  QObject::connect(FTimer, &QTimer::timeout, this, [this]() { Animate(); });
  setFixedSize(32, 32);
}

void FrameAnimation::Init(const QString & Name)
{
  FName = Name;
  // The size matching the screen scaling (like GetAnimationsImages by PixelsPerInch)
  int Wanted = qRound(32 * DevicePixelRatio(this));
  int Size = AnimationSizes[0];
  for (int S : AnimationSizes)
  {
    if (S <= Wanted)
    {
      Size = S;
    }
  }
  FFrames = Icons::AnimationFrames(Name, Size);
  for (Icons::AnimationFrame & Frame : FFrames)
  {
    Frame.Pixmap.setDevicePixelRatio(Size / 32.0);
  }
  FFirstLoopFrame = -1;
  for (int Index = 0; Index < FFrames.size(); Index++)
  {
    if (FFrames[Index].Index > 0)
    {
      FFirstLoopFrame = Index;
      break;
    }
  }
  if (FFirstLoopFrame < 0)
  {
    FFirstLoopFrame = 0;
  }
  Stop();
}

void FrameAnimation::Start()
{
  if (!FFrames.isEmpty())
  {
    FTimer->start(FFrames[FCurrentFrame].Duration);
  }
}

void FrameAnimation::Stop()
{
  FTimer->stop();
  FCurrentFrame = FFrames.isEmpty() ? -1 : 0;
  update();
}

void FrameAnimation::Animate()
{
  if (!FFrames.isEmpty())
  {
    if (FCurrentFrame >= FFrames.size() - 1)
    {
      FCurrentFrame = FFirstLoopFrame;
    }
    else
    {
      FCurrentFrame++;
    }
    update();
    FTimer->start(FFrames[FCurrentFrame].Duration);
  }
}

QSize FrameAnimation::sizeHint() const
{
  return QSize(32, 32);
}

void FrameAnimation::paintEvent(QPaintEvent * /*Event*/)
{
  if ((FCurrentFrame >= 0) && (FCurrentFrame < FFrames.size()))
  {
    QPainter Painter(this);
    Painter.drawPixmap(QRect(0, 0, 32, 32), FFrames[FCurrentFrame].Pixmap);
  }
}
